snSoundJob::snSoundJob()
{
	Init();
}


//========================================================================
//========================================================================
snSoundJob::snSoundJob( const snSoundJob& i_CopyFrom )
{
	*this = i_CopyFrom;
}


//========================================================================
//========================================================================
snSoundJob::~snSoundJob()
{
	//Delete();
}


//========================================================================
//	SetName()
//========================================================================
void	
snSoundJob::SetName( const itString i_Name )
{
	m_Name = i_Name;
}


//========================================================================
//	GetName()
//========================================================================
itString	
snSoundJob::GetName() const
{
	return m_Name;
}


//========================================================================
//	GetTypeMask()
//========================================================================
unsigned long 
snSoundJob::GetTypeMask() const
{
	return m_TypeMask;
}


//========================================================================
//	SetTypeMask()
//========================================================================
void snSoundJob::SetTypeMask( const unsigned long i_TypeMask )
{
	m_TypeMask	= i_TypeMask;
}


//========================================================================
//========================================================================
bool 
snSoundJob::IsTypeMaskEqual( const unsigned long i_TypeMask )
{
	return ( (i_TypeMask & m_TypeMask) == i_TypeMask );
}


//========================================================================
//	Init()
//========================================================================
void	
snSoundJob::Init()
{
	m_TypeMask	= 0x0;
}
