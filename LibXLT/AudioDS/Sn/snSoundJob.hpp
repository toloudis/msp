#ifdef SN_SOUNDJOB_HPP
#error snSoundJob.hpp multiply included
#endif
#define SN_SOUNDJOB_HPP

#ifndef IT_STRING_HPP
#include "Core/it/itString.hpp"
#endif


//============================================================================
//	Forward reference
//============================================================================
class fsLocator;


//============================================================================
//============================================================================
class snSoundJob
{
	public:
	//----------------------------------------------------------------------------
	//	Constructors and Destructors
	//----------------------------------------------------------------------------

		//========================================================================
		//	default and copy constructors
		//========================================================================
		snSoundJob();
		snSoundJob( const snSoundJob& i_CopyFrom );

		//========================================================================
		//========================================================================
		virtual ~snSoundJob();


	//----------------------------------------------------------------------------
	//	Functions
	//----------------------------------------------------------------------------

		//========================================================================
		//	Load()
		//========================================================================
		virtual void	Load() {}

		//========================================================================
		//	Free()
		//========================================================================
		virtual void	Free() {}

		//========================================================================
		//	Reload()
		//
		//		Reload the raw sound data and resume the sound
		//========================================================================
		virtual void	Reload() {};

		//========================================================================
		//	Unload()
		//
		//		Pause the sound and unload the raw sound data
		//========================================================================
		virtual void	Unload(bool i_bReloadOnStart = false) {};

		//========================================================================
		//	Delete()
		//========================================================================
		virtual void	Delete() {}

		//========================================================================
		//	Start()
		//========================================================================
		virtual void	Start( float i_SimulationTime ) {}

		//========================================================================
		//	Restart()
		//========================================================================
		virtual void	Restart( float i_SimulationTime ) {}

		//========================================================================
		//	Stop()
		//========================================================================
		virtual void	Stop() {}

		//========================================================================
		//	Pause()
		//========================================================================
		virtual void	Pause() {}

		//========================================================================
		//	Resume()
		//========================================================================
		virtual void	Resume( float i_SimulationTime ) {}

		//========================================================================
		//	Think()
		//========================================================================
		virtual void	Think( float i_SimulationTime ) {}

		//========================================================================
		//	IsPlaying()
		//
		//	return true if the sound job is currently playing.
		//========================================================================
		virtual bool	IsPlaying() const { return true; };


	//----------------------------------------------------------------------------
	//	Volume Functions
	//----------------------------------------------------------------------------

		//========================================================================
		//	Volume
		//
		//	The volume can range from 0.0 (silent) to 1.0 (full-on)
		//========================================================================
		virtual void		SetVolume( const float i_NewVolume ) {}
		virtual float		GetVolume() const { return 1.0f; }

		//========================================================================
		//	VolumeGlobalFactor
		//
		//	The volume factor (percentage) can range from 0.0 (0%) to 1.0 (100 %)
		//========================================================================
		virtual void		SetVolumeGlobalFactor( const float i_Value ) {}
		virtual float		GetVolumeGlobalFactor() const {return 1.0f; };

		//========================================================================
		//	SetVolumeTypeFactor()
		//
		//	The volume factor (percentage) can range from 0.0 (0%) to 1.0 (100 %)
		//========================================================================
		virtual void		SetVolumeTypeFactor( const float i_Value ) {};

		//========================================================================
		//	GetVolumeTypeFactor()
		//
		//	The volume factor (percentage) can range from 0.0 (0%) to 1.0 (100 %)
		//========================================================================
		virtual float		GetVolumeTypeFactor() const { return 1.0f; };

		//========================================================================
		//	GetVolumeFinal()
		//
		//	The final volume value based on the base volume and all factors.
		//========================================================================
		virtual float		GetVolumeFinal() const { return 1.0f; };



	//----------------------------------------------------------------------------
	//	Data accessor functions
	//----------------------------------------------------------------------------

		//========================================================================
		//	DeleteWhenFinished
		//========================================================================
		inline virtual bool	IsDeleteWhenFinished() const				{ return false; }
		inline virtual void	SetDeleteWhenFinished( const bool Value )	{ }

		//========================================================================
		//	Finished
		//========================================================================
		inline virtual bool	IsFinished() const						{ return false; }
		inline virtual void	SetFinished( const bool Value )			{ }


	//----------------------------------------------------------------------------
	//	Accessor Functions
	//----------------------------------------------------------------------------

		//========================================================================
		//	Filename
		//========================================================================
		virtual void	SetFilename( const fsLocator & Filename )	{};

		//========================================================================
		//	Name
		//========================================================================
		void		SetName( const itString i_Name );
		itString	GetName() const;

		//========================================================================
		//	TypeMask
		//========================================================================
		virtual unsigned long GetTypeMask() const;
		virtual void SetTypeMask( const unsigned long i_TypeMask );
		virtual bool IsTypeMaskEqual( const unsigned long i_TypeMask );

		//========================================================================
		//	SetLoops()
		//
		//	Set the number of loops to play a sound.
		//	-1 (or any negative number) means infinite.
		//
		//	Note: currently it only signifies whether a sound is looping or not.
		//	it doesn't do counting.
		//========================================================================
		virtual void SetLoops( const int i_Value ) {};

		//========================================================================
		//	GetLoops()
		//	
		//	Get the number of loops to play a sound.
		//
		//	Note: currently it only signifies whether a sound is looping or not.
		//	it doesn't do counting.
		//========================================================================
		virtual int			GetLoops() const { return 0; };

	private:
		//========================================================================
		//	Init()
		//========================================================================
		void	Init();


	//----------------------------------------------------------------------------
	//	Member Data
	//----------------------------------------------------------------------------

		itString	m_Name;

		//	The type mask is a way to mark sounds as being of a certain type.
		//	These values are set by an application but there are standard types
		//	that the SoundManager uses.
		//
		unsigned long		m_TypeMask;

};
