#ifdef SN_PLAYLIST_HPP
#error snPlaylist.hpp multiply included
#endif
#define SN_PLAYLIST_HPP

#include <vector>


//----------------------------------------------------------------------------
//	Forward references
//----------------------------------------------------------------------------
class fsLocator;


//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
class snPlaylist
{
	public:

		//====================================================================
		// Constructor
		//====================================================================
		snPlaylist();

		//====================================================================
		// Destructor
		//====================================================================
		~snPlaylist();

		//====================================================================
		// Add a song to a playlist
		//====================================================================
		void Add(fsLocator& i_Song);

		//====================================================================
		// Clear the playlist
		//====================================================================
		void Clear();

		//====================================================================
		//	Get whether the playlist is shuffled
		//====================================================================
		bool GetShuffle();

		//====================================================================
		//	Set whether the playlist is shuffled
		//====================================================================
		void SetShuffle(bool i_bShuffle);

		//====================================================================
		//	Get the playlist current volume
		//====================================================================
		float GetVolume();

		//====================================================================
		//	Set the playlist current volume
		//====================================================================
		void SetVolume( float i_Volume );

		//====================================================================
		// NumSongs()
		// return the number of songs in the list.
		//====================================================================
		int NumSongs() const;

		//====================================================================
		// GetSong()
		// Get a specific song by #
		//====================================================================
		const fsLocator& GetSong(int i_SongNum) const;

		//====================================================================
		// Get the current song by locator
		//====================================================================
		const fsLocator& GetCurrentSong() const;

		//====================================================================
		//	Set the playlist current song
		//====================================================================
		void SetSong( int i_SongNum );

		//====================================================================
		//	Go the next song
		//====================================================================
		bool NextSong();

		//====================================================================
		//	Go the previous song
		//====================================================================
		bool PrevSong();


	private:

		std::vector<fsLocator>	m_Playlist;
		std::vector<int>	m_ShuffledPlaylist;
		int		m_CurrentSong;
		float	m_Volume;
		bool m_bShuffled;
};
