#include "Core/app/appEvent.hpp"


//--------------------------------------------------------------------
//--------------------------------------------------------------------
appEvent::appEvent()
:	m_bConsumed(false)
{
}

//--------------------------------------------------------------------
//--------------------------------------------------------------------
appEvent::~appEvent()
{
}

//--------------------------------------------------------------------
//	Call Consume() when you don't want anyone after you to receive
//	the event.
//--------------------------------------------------------------------
void appEvent::Consume()
{
	m_bConsumed = true;
}

//--------------------------------------------------------------------
//	WasConsumed() returns true only if someone has called Consume()
//	on the event.
//--------------------------------------------------------------------
bool appEvent::WasConsumed() const
{
	return m_bConsumed;
}

