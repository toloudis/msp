#ifndef APP_EVENT_HPP
#include "Core/app/appEvent.hpp"
#endif


//============================================================================
//	appStartEvents are posted (once) when the application starts.
//============================================================================
class appStartEvent : public appEvent
{
	public:

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		appStartEvent();

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		virtual ~appStartEvent();
};

//============================================================================
//	appStopEvents are posted (once) when the application is quitting.
//============================================================================
class appStopEvent : public appEvent
{
	public:

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		appStopEvent();

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		virtual ~appStopEvent();
};

//============================================================================
//	an appSuspendEvent is posted whenever the application loses focus or
//	is suspended for some reason (alt-tab).
//============================================================================
class appSuspendEvent : public appEvent
{
	public:

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		appSuspendEvent();

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		virtual ~appSuspendEvent();
};

//============================================================================
//	an appResumeEvent is posted when the application regains focus after
//	being suspended.
//============================================================================
class appResumeEvent : public appEvent
{
	public:

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		appResumeEvent();

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		virtual ~appResumeEvent();
};

//============================================================================
//	an appQuitRequestEvent is posted when the user tries to do something
//	to instantly terminate the application (alt-f4).
//============================================================================
class appQuitRequestEvent : public appEvent
{
	public:

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		appQuitRequestEvent();

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		virtual ~appQuitRequestEvent();
};
