inline float* maVector2d::Ptr() const
{
	// look out! this amounts to a const_cast.
	// oh well, we know what we're doing, right?
	return (float*)&m_X;
}
inline const float* maVector2d::GetPtr() const
{
	return &m_X;
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
float
maVector2d::Length() const						// LENGTH OF VECTOR
{
	return ( (float)sqrt( m_X*m_X + m_Y*m_Y ) );
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
float 
maVector2d::LengthSqr() const					// LENGTH OF VECTOR (SQUARED)
{
	return ( m_X*m_X + m_Y*m_Y );
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maVector2d::Normalize()							// NORMALIZE VECTOR
{
	float L = this->Length();
	
	//	Divide the vector by the length
	//
	if ( L > 0 )
	{ 
		m_X /= L;
		m_Y /= L;
	}
}

//------------------------------------------------------------------------
//	Equal Value - are the values equal within a tolerance
//------------------------------------------------------------------------
inline bool maVector2d::Equal(const maVector2d& i_Value1, const float i_Tolerance) const
{
	return (   (fabs(m_X - i_Value1.m_X) < i_Tolerance)
			&& (fabs(m_Y - i_Value1.m_Y) < i_Tolerance));
}

//------------------------------------------------------------------------
//	operator << performs writing to an ostream
//------------------------------------------------------------------------
inline std::ostream& operator << (std::ostream& io_os, const maVector2d& i_Vector)
{
	io_os << i_Vector.m_X << "," << i_Vector.m_Y;
	return io_os;
}
