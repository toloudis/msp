maVector4d&
maVector4d:: operator = ( const maVector4d& i_A )            // ASSIGNMENT (=)
{ 
	m_X	= i_A.m_X;
	m_Y	= i_A.m_Y;
	m_Z	= i_A.m_Z;
	m_W	= i_A.m_W; 

	return(*this);  
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
maVector4d 
maVector4d::operator + ( const maVector4d& i_A ) const       // ADDITION (+)
{ 
	maVector4d Sum( m_X + i_A.m_X, m_Y + i_A.m_Y, m_Z + i_A.m_Z, m_W + i_A.m_W );

	return Sum; 
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
maVector4d 
maVector4d::operator - ( const maVector4d& i_A ) const       // SUBTRACTION (-)
{ 
	maVector4d Diff(m_X-i_A.m_X, m_Y-i_A.m_Y, m_Z-i_A.m_Z, m_W-i_A.m_W);

	return Diff; 
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
float 
maVector4d::operator * ( const maVector4d& i_A ) const       // DOT-PRODUCT (*)
{ 
	float o_DotProd = m_X*i_A.m_X + m_Y*i_A.m_Y + m_Z*i_A.m_Z + m_W*i_A.m_W; 

	return o_DotProd; 
}


