//------------------------------------------------------------------------
//------------------------------------------------------------------------
float 
maVector4d::operator [] ( const int i_Index ) const         // ALLOWS VECTOR ACCESS AS AN ARRAY.
{  
	switch (i_Index)
	{
		case 0:
			return m_X;
		case 1:
			return m_Y;
		case 2:
			return m_Z;
		case 3:
			return m_W;
		default:
			DBG_ASSERT(false, "Index out of range - " << i_Index);
			return 0.0f;
	}
}

