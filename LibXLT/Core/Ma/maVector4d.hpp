//------------------------------------------------------------------------
//------------------------------------------------------------------------
bool 
maVector4d::operator == ( const maVector4d& i_A ) const	  // COMPARISON OPERATOR
{ 
	return ((m_X == i_A.m_X) && (m_Y == i_A.m_Y) && (m_Z == i_A.m_Z) && (m_W == i_A.m_W)) ? true : false;	
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
inline bool 
maVector4d::operator != ( const maVector4d& i_A ) const
{
	return  (m_X != i_A.m_X) || 
			(m_Y != i_A.m_Y) || 
			(m_Z != i_A.m_Z) || 
			(m_W != i_A.m_W);
}

