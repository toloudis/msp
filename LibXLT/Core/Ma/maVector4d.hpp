//------------------------------------------------------------------------
//------------------------------------------------------------------------
float 
maVector4d::Length() const                     // LENGTH OF VECTOR
{ 
	return ( (float)sqrt( m_X*m_X + m_Y*m_Y + m_Z*m_Z + m_W*m_W ) ); 
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
float 
maVector4d::LengthSqr() const                  // LENGTH OF VECTOR (SQUARED)
{ 
	return (m_X*m_X + m_Y*m_Y + m_Z*m_Z + m_W*m_W ); 
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
bool 
maVector4d::Normalize()							 // NORMALIZE VECTOR
{ 
	float L = this->Length();
	
	//	Divide the vector by the length
	//
	if ( L > 1.0e-6 ) 
	{ 
		m_X	/= L; 
		m_Y	/= L; 
		m_Z	/= L; 
		m_W	/= L; 

		return true;
	}

	return false;
}


//------------------------------------------------------------------------
//	Equal Value - are the values equal within a tolerance
//------------------------------------------------------------------------
inline bool maVector4d::Equal(const maVector4d& i_Value1, const float i_Tolerance) const
{
	return (   (fabs(m_X - i_Value1.m_X) < i_Tolerance)
			&& (fabs(m_Y - i_Value1.m_Y) < i_Tolerance)
			&& (fabs(m_Z - i_Value1.m_Z) < i_Tolerance)
			&& (fabs(m_W - i_Value1.m_W) < i_Tolerance));
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maVector4d::Wdiv()
{ 
	m_X	/= m_W;
	m_Y	/= m_W;
	m_Z	/= m_W;
	m_W	= 1; 
}

