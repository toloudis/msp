		//------------------------------------------------------------------------
		//------------------------------------------------------------------------
		inline void Set( float i_X, float i_Y, float i_Z );

		//------------------------------------------------------------------------
		//------------------------------------------------------------------------
		inline void Set( float i_v[3] );

		//------------------------------------------------------------------------
		//------------------------------------------------------------------------
		inline maVector3d& operator = ( const maVector3d& i_A );
    
		//------------------------------------------------------------------------
