//------------------------------------------------------------------------
//	free operator functions
//------------------------------------------------------------------------
//------------------------------------------------------------------------
inline maIntPoint2d operator * ( const maIntPoint2d& i_Vector, int i_s )
{
	return maIntPoint2d( i_Vector.m_X * i_s, i_Vector.m_Y * i_s );
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
inline maIntPoint2d operator * ( int i_s, const maIntPoint2d& i_Vector )
{
	return maIntPoint2d( i_Vector.m_X * i_s, i_Vector.m_Y * i_s );
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
inline maIntPoint2d operator / ( const maIntPoint2d& i_Vector, int i_s )
{
	return maIntPoint2d( i_Vector.m_X / i_s, i_Vector.m_Y / i_s );
}



//------------------------------------------------------------------------
//	default constructors
//------------------------------------------------------------------------
inline maIntPoint2d::maIntPoint2d()
{
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
inline maIntPoint2d::~maIntPoint2d()
{
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
int 
maIntPoint2d::GetX() const
{
	return m_X;
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
int 
maIntPoint2d::GetY() const
{
	return m_Y;
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maIntPoint2d::SetX( int i_X )
{
	m_X	= i_X;
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maIntPoint2d::SetY( int i_Y )
{
	m_Y	= i_Y;
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maIntPoint2d::Set( int i_X, int i_Y )
{ 
	m_X	= i_X; 
	m_Y	= i_Y; 
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maIntPoint2d::Set( int i_v[2] )
{ 
	m_X	= i_v[0];
	m_Y	= i_v[1];
}
 
//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maIntPoint2d::Set( const maIntPoint2d& i_vec2d )
{
	m_X	= i_vec2d.GetX();
	m_Y	= i_vec2d.GetY();
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
maIntPoint2d&
maIntPoint2d:: operator = ( const maIntPoint2d& i_A )            // ASSIGNMENT (=)
{ 
	m_X	= i_A.GetX();
	m_Y	= i_A.GetY();

	return(*this);  
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
maIntPoint2d 
maIntPoint2d::operator + ( const maIntPoint2d& i_A ) const       // ADDITION (+)
{ 
	maIntPoint2d Sum( m_X + i_A.GetX(), m_Y + i_A.GetY() );

	return Sum; 
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
maIntPoint2d 
maIntPoint2d::operator - ( const maIntPoint2d& i_A ) const       // SUBTRACTION (-)
{ 
	maIntPoint2d Diff( m_X-i_A.GetX(), m_Y-i_A.GetY() );

	return Diff; 
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
bool 
maIntPoint2d::operator == ( const maIntPoint2d& i_A ) const	  // COMPARISON OPERATOR
{ 
	return ( (m_X == i_A.GetX()) && (m_Y == i_A.GetY()) ) ? true : false;	
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
bool 
maIntPoint2d::operator != ( const maIntPoint2d& i_A ) const	  // NOT COMPARISON OPERATOR
{ 
	return ( (m_X != i_A.GetX()) || (m_Y != i_A.GetY()) ) ? true : false;	
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maIntPoint2d::operator += ( const maIntPoint2d& i_A )              // ACCUMULATED VECTOR ADDITION (+=)
{ 
	m_X	+= i_A.GetX(); 
	m_Y	+= i_A.GetY();
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maIntPoint2d::operator -= ( const maIntPoint2d& i_A )              // ACCUMULATED VECTOR SUBTRACTION (+=)
{ 
	m_X	-= i_A.GetX();
	m_Y	-= i_A.GetY(); 
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maIntPoint2d::operator *= ( int i_s )              // ACCUMULATED SCALAR MULT (*=)
{ 
	m_X	*= i_s;
	m_Y	*= i_s;
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
void 
maIntPoint2d::operator /= ( int i_s )              // ACCUMULATED SCALAR DIV (/=)
{ 
	m_X	/= i_s;
	m_Y	/= i_s;
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
maIntPoint2d 
maIntPoint2d::operator - () const                 // NEGATION (-)
{ 
	maIntPoint2d o_Negated( -m_X, -m_Y );

	return o_Negated;
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
int 
maIntPoint2d::operator [] ( int i_Index ) const         // ALLOWS VECTOR ACCESS AS AN ARRAY.
{  
	switch (i_Index)
	{
		case 0:
			return m_X;
		case 1:
			return m_Y;
		default:
			DBG_ASSERT(false, "Index out of range - " << i_Index);
			//throw Rob();
			return 0;
	}
}
