#include "Core/ma/maIntPoint2d.hpp"


//------------------------------------------------------------------------
//	Constructor
//------------------------------------------------------------------------
maIntPoint2d::maIntPoint2d( int i_X, int i_Y )
{
	m_X	= i_X;
	m_Y	= i_Y;
}


//------------------------------------------------------------------------
//	Constructor
//------------------------------------------------------------------------
maIntPoint2d::maIntPoint2d( int i_v[2] )
{ 
	m_X	= i_v[0];
	m_Y	= i_v[1];
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
maIntPoint2d::maIntPoint2d( const maIntPoint2d& i_CopyFrom )
{
	m_X	= i_CopyFrom.GetX();
	m_Y	= i_CopyFrom.GetY();
}
