#include "Core/ma/maVector2d.hpp"


//------------------------------------------------------------------------
//	Constructor
//------------------------------------------------------------------------
maVector2d::maVector2d( float i_X, float i_Y )
{
	m_X	= i_X;
	m_Y	= i_Y;
}


//------------------------------------------------------------------------
//	Constructor
//------------------------------------------------------------------------
maVector2d::maVector2d( float i_v[2] )
{ 
	m_X	= i_v[0];
	m_Y	= i_v[1];
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
maVector2d::maVector2d( const maVector2d& i_CopyFrom )
{
	m_X	= i_CopyFrom.GetX();
	m_Y	= i_CopyFrom.GetY();
}
