#include "Core/ma/maVector4d.hpp"

#include "Core/ma/maVector3d.hpp"


//------------------------------------------------------------------------
//	Constructor
//------------------------------------------------------------------------
maVector4d::maVector4d( float i_X, float i_Y, float i_Z, float i_W )
{
	m_X	= i_X;
	m_Y	= i_Y;
	m_Z	= i_Z;
	m_W	= i_W; 
}


//------------------------------------------------------------------------
//	Constructor
//------------------------------------------------------------------------
maVector4d::maVector4d( float i_v[4] )
{ 
	m_X	= i_v[0];
	m_Y	= i_v[1];
	m_Z	= i_v[2];
	m_W	= i_v[3]; 
}

//------------------------------------------------------------------------
//	Constructor
//------------------------------------------------------------------------
maVector4d::maVector4d( const maVector3d& i_v, float i_w )
{
	m_X	= i_v[0];
	m_Y	= i_v[1];
	m_Z	= i_v[2];
	m_W	= i_w; 
}

//------------------------------------------------------------------------
//	default constructors
//------------------------------------------------------------------------
maVector4d::maVector4d()
:	m_X(0),
	m_Y(0),
	m_Z(0),
	m_W(0)
{
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
maVector4d::maVector4d( const maVector4d& i_CopyFrom )
{
	m_X	= i_CopyFrom.GetX();
	m_Y	= i_CopyFrom.GetY();
	m_Z	= i_CopyFrom.GetZ();
	m_W	= i_CopyFrom.GetW();
}


//------------------------------------------------------------------------
//------------------------------------------------------------------------
maVector4d::~maVector4d()
{
}

maVector3d maVector4d::XYZ()
{
	return maVector3d(m_X,m_Y,m_Z);
}
