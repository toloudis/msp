#include "Core/fs/fsLocator.hpp"
#endif
#ifndef NAME_STRING_HPP
#include "Core/name/nameString.hpp"
#endif

#include <vector>


//============================================================================
//	resource data for a single file in the list
//============================================================================
class fsResourceTrackerFileData
{
public:
	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	fsResourceTrackerFileData();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void OnOpen( const fsLocator& i_File );

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void OnClose();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void DecrementDepth();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void IncrementDepth();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void SetDepth( int i_Depth );

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	int GetDepth() const;

	//------------------------------------------------------------------------
	//	Increment the reference count and return the new count
	//------------------------------------------------------------------------
	int IncrementReferenceCount();

	//------------------------------------------------------------------------
	//	decrement the reference count and return the new count
	//------------------------------------------------------------------------
	int DecrementReferenceCount();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	int GetReferenceCount() const;

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void SetFilePath(const fsLocator& i_FileName);

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void SetFilePath(const itString& i_FileName);

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	const fsLocator& GetFilePath() const;

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	const itString& GetFileName() const;

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	bool IsOpen();

	//------------------------------------------------------------------------
	//	Set the name of this resource.  If there is not a file, but only a 
	//	name, it is an category or object name.
	//------------------------------------------------------------------------
	void SetName( const nameString& i_Name );

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	nameString GetName() const;

	//------------------------------------------------------------------------
	//	Set the flag to signify the name is the name of the object (as 
	//	opposed to a material, fragment, etc).
	//------------------------------------------------------------------------
	void SetObjectName(bool i_bObjectName);
	bool IsObjectName() const;

private:
	fsLocator	m_File;
	int			m_Depth;
	bool		m_bOpen;
	int			m_ReferenceCount;

	nameString	m_Name;
	bool		m_bObjectName;
};


//============================================================================
//	typedefs
//============================================================================
typedef std::vector<fsResourceTrackerFileData> fsResourceTrackerDataList;


//============================================================================
//	Main resource data class
//============================================================================
class fsResourceTrackerData
{
public:
	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	fsResourceTrackerDataList& GetList();

	//------------------------------------------------------------------------
	//	add a node with a filename
	//------------------------------------------------------------------------
	void Add(const fsLocator& i_FilePath);

	//------------------------------------------------------------------------
	//	add a node with a name (not filename)
	//------------------------------------------------------------------------
	void Add(const nameString& i_Name, bool i_bIsObjectName = false);

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void operator =(const fsResourceTrackerData& i_Data);

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void operator +=(const fsResourceTrackerData& i_Data);

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void DecrementCurrentDepth();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void IncrementCurrentDepth();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void SetCurrentDepth( int i_Depth );

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	int GetCurrentDepth() const;

public:
	int	m_Depth;	// this is the "global" current depth
	fsResourceTrackerDataList m_Resources;
};

