//============================================================================
// Debug Stream 
//============================================================================
namespace dbgData
{
	struct StreamData
	{
		bool m_canLog;
		bool m_canWarn;
		bool m_canError;
		bool m_canTrace;
		bool m_writeCSV;
		bool m_WriteTime_Date;
		bool m_WriteThreadID;
		bool m_WriteFileName_Line;
		bool m_WriteLevel;
		bool m_WriteFilePath;
	};

}


//============================================================================
//============================================================================
class dbgStream
{
	public:
		//----------------------------------------------------------------
		// assigns a name and stream to the instance
		//----------------------------------------------------------------
		dbgStream(std::wstring& i_Name, std::ostream* i_Stream);

		//----------------------------------------------------------------
		// deconstructor
		//----------------------------------------------------------------
		~dbgStream();

		//----------------------------------------------------------------
		// returns whether or not this stream is active.
		//----------------------------------------------------------------
		bool isStreamActive();

		//----------------------------------------------------------------
		// Sets the activation level for the stream
		//----------------------------------------------------------------
		void setStreamActive( bool i_IsActive );
		
		//----------------------------------------------------------------
		//----------------------------------------------------------------
		void setFileName( bool i_WriteFile );

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		void setTimeStamp( bool i_WriteTime );

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		void setDbgLevel( bool i_WriteLevel );

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		void setThreadID( bool i_WriteThread );

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		bool logEnabled();

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		void enableLog( bool doLog );

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		bool warningEnabled();

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		void enableWarning( bool doWarning );
		
		//----------------------------------------------------------------
		//----------------------------------------------------------------
		bool errorEnabled();

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		void enableError( bool doError );

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		bool traceEnabled();

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		void enableTrace( bool doTrace );

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		bool csvEnabled();

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		void enableCSV( bool doCSV );

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		bool filePathEnabled();

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		void enableFilePath( bool doWriteFilePath );

		//----------------------------------------------------------------
		//----------------------------------------------------------------
		dbgData::StreamData* GetData();

		//----------------------------------------------------------------
		// return the stream belonging to this instance
		//----------------------------------------------------------------
		std::ostream* GetStream();
		
		//----------------------------------------------------------------
		// Use the name as an ID for this instance
		//----------------------------------------------------------------
		std::wstring GetName();

	private:
		std::wstring m_Name;
		std::ostream* m_Stream;
		dbgData::StreamData* m_Data;
		bool m_IsActive;
}; //end class definition

