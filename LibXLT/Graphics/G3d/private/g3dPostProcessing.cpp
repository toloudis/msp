#include "Graphics/g3d/g3dPostProcessing.hpp"

#include "Graphics/eff/effShaderParams.hpp"

//============================================================================
//============================================================================
namespace g3dPostProcessing
{
	namespace
	{
		shared_ptr<effShaderParams> l_CurrentEffect;

		bool l_bActive = false;
	}

	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	void SetActive(bool i_bActive)
	{
		l_bActive = i_bActive;
	}

	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	bool GetActive()
	{
		return l_bActive;
	}

	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	void SetPostEffect(shared_ptr<effShaderParams> i_ShaderParams)
	{
		l_CurrentEffect = i_ShaderParams;
	}

	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	shared_ptr<effShaderParams> GetPostEffect()
	{
		return l_CurrentEffect;
	}

}

