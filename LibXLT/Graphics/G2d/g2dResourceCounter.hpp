#define G2D_RESOURCECOUNTER_HPP


//============================================================================
//============================================================================
class g2dResourceCounterImpl;


//============================================================================
// all memory counts in KB
//============================================================================
class g2dResourceCounter
{
public:
	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static float GetTotalVideoMemory();
	
	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static float GetTotalSceneTextureMemory();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static int GetNumSceneTextures();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static float GetTotalFramebufferMemory();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static int GetNumFramebufferTextures();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static float GetTotalShadowMapMemory();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static int GetNumShadowMapTextures();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static float GetTotalVertexBufferMemory();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static int GetNumVertexBuffers();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static float GetTotalIndexBufferMemory();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	static int GetNumIndexBuffers();

	//--------------------------------------------------------------------
	// Set new implementation method, returns pointer to last one
	// that was being used.  Both can be NULL.
	// Ownership for the pointer remains with the caller.
	//--------------------------------------------------------------------
	static g2dResourceCounterImpl* SetImplementation(g2dResourceCounterImpl* i_pCreator);

private:
	static g2dResourceCounterImpl* sm_pImplementation;
};


//============================================================================
//============================================================================
class g2dResourceCounterImpl
{
public:
	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual float GetTotalVideoMemory() = 0;
	
	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual float GetTotalSceneTextureMemory() = 0;

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual int GetNumSceneTextures() = 0;

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual float GetTotalFramebufferMemory() = 0;

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual int GetNumFramebufferTextures() = 0;

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual float GetTotalShadowMapMemory() = 0;

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual int GetNumShadowMapTextures() = 0;

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual float GetTotalVertexBufferMemory() = 0;

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual int GetNumVertexBuffers() = 0;

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual float GetTotalIndexBufferMemory() = 0;

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual int GetNumIndexBuffers() = 0;
};
