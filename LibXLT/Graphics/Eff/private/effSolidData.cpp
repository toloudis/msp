#include "Graphics/eff/effSolidData.hpp"


//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
effSolidData::effSolidData()
:	m_Color(1.0f, 1.0f, 1.0f, 1.0f)
{
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
effSolidData::~effSolidData()
{
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
effSolidData::effSolidData(const effSolidData& i_CopyFrom)
{
	(*this) = i_CopyFrom;
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
effSolidData& effSolidData::operator = (const effSolidData& i_CopyFrom)
{
	if (&i_CopyFrom == this)
		return *this;

	effShaderData::operator =(i_CopyFrom);
	m_Color = i_CopyFrom.m_Color;
	return *this;
}
