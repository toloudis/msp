<#
    EmbedShadersVk.ps1

    The Vulkan counterpart of GraphicsDX11's EmbedShaders.ps1: for every
    *.effect.json under -ShaderDir it compiles each entry point the manifest
    lists with DXC to SPIR-V, then writes one C++ file (namespace gvk)
    holding the manifests and the SPIR-V as byte arrays. GraphicsVulkan's
    fxEmbeddedShadersVk.cpp includes that file.

    The shaders are GraphicsDX11's, copied unchanged; everything that makes
    them work on Vulkan is a compiler option. The same options are used by
    the GraphicsTests shader build step (GraphicsTests.vcxproj) and by
    Tools/fx2hlsl/compile_check.py --spirv; keep the three in step.

    -TableName names the generated table (default fxEmbeddedShadersVk, i.e.
    fxEmbeddedShadersVk::k_Effects). -Deferred lists "<file>|<entry>" stages
    that DXC can't compile yet; they are skipped (and listed in the table's
    k_Deferred) instead of failing the build.

    Called from GraphicsVulkan.vcxproj (target EmbedVkShaders) before
    compiling. Written for Windows PowerShell 5.1.
#>
param(
    [Parameter(Mandatory = $true)][string]$ShaderDir,
    [Parameter(Mandatory = $true)][string]$OutFile,
    [Parameter(Mandatory = $true)][string]$Dxc,
    [string]$TableName = "fxEmbeddedShadersVk",
    # Hair_HS uses ProcessIsolineTessFactors, which DXC's SPIR-V backend lacks (Plan 7)
    [string[]]$Deferred = @("Materials/Hair_SH.hlsl|Hair_HS", "Special/HairDefault.hlsl|Hair_HS", "Special/OpacityRender.hlsl|Hair_HS")
)

$ErrorActionPreference = "Stop"

# GraphicsVulkan's DXC options (see the header comment and vkd/vkdBindings.hpp):
# register shifts for the descriptor-heap binding table, D3D constant buffer
# layout, D3D's SV_Position.w and SV_VertexID/SV_InstanceID meanings. Y is
# flipped with a negative viewport height, so no -fvk-invert-y.
$DxcOptions = @(
    "-spirv", "-fspv-target-env=vulkan1.3", "-fvk-use-dx-layout", "-fvk-use-dx-position-w",
    "-fvk-support-nonzero-base-instance", "-fvk-support-nonzero-base-vertex",
    "-fvk-b-shift", "0", "0", "-fvk-t-shift", "100", "0", "-fvk-s-shift", "200", "0", "-fvk-u-shift", "300", "0"
)

if (-not (Test-Path $Dxc)) { throw "dxc.exe not found at '$Dxc'" }

# C++ initializer list for a byte array, 32 bytes per line.
function Format-Bytes([byte[]]$bytes) {
    $sb = New-Object System.Text.StringBuilder
    for ($i = 0; $i -lt $bytes.Length; $i += 32) {
        $n = [Math]::Min(32, $bytes.Length - $i)
        $hex = [BitConverter]::ToString($bytes, $i, $n)
        [void]$sb.Append("`t0x").Append($hex.Replace("-", ",0x")).Append(",`r`n")
    }
    return $sb.ToString()
}

function Stage-Entries($stages) {
    foreach ($p in $stages.PSObject.Properties) {
        if ($null -ne $p.Value) { $p.Value }
    }
}

$ShaderDir = (Resolve-Path $ShaderDir).Path
$tmp = [IO.Path]::GetTempFileName()

$out = New-Object System.Text.StringBuilder
[void]$out.Append("// Generated by EmbedShadersVk.ps1 from the *.effect.json files under`r`n")
[void]$out.Append("// $($ShaderDir.Replace('\', '/')). Do not edit.`r`n`r`n")
[void]$out.Append("namespace gvk`r`n{`r`nnamespace`r`n{`r`n")

$effects = @()
$skipped = @()
$withGlobals = @()
$warnings = 0
$manifests = Get-ChildItem -Path $ShaderDir -Filter *.effect.json -Recurse | Sort-Object FullName
$e = 0
try {
    foreach ($file in $manifests) {
        $text = [IO.File]::ReadAllText($file.FullName)
        $manifest = $text | ConvertFrom-Json
        $hlsl = Join-Path $file.DirectoryName $manifest.hlsl
        $hlslRel = $hlsl.Substring($ShaderDir.Length).TrimStart('\', '/') -replace '\\', '/'
        $prefix = "k_e$e"

        # the manifest, NUL-terminated
        $jsonBytes = [Text.Encoding]::UTF8.GetBytes($text) + [byte]0
        [void]$out.Append("const unsigned char ${prefix}_manifest[] = {`r`n").Append((Format-Bytes $jsonBytes)).Append("};`r`n")

        # one SPIR-V blob per unique entry point + profile (the manifest's profile is the key)
        $seen = @{}
        $table = @()
        foreach ($tech in $manifest.techniques) {
            foreach ($pass in $tech.passes) {
                foreach ($stage in (Stage-Entries $pass.stages)) {
                    $key = "$($stage.entry)|$($stage.profile)"
                    if ($seen.ContainsKey($key)) { continue }
                    $seen[$key] = $true

                    if ($Deferred -contains "$hlslRel|$($stage.entry)") {
                        $skipped += "$hlslRel|$($stage.entry)"
                        continue
                    }

                    $profile = $stage.profile.Split("_")[0] + "_6_0"
                    # dxc writes warnings to stderr; with "Stop", PowerShell 5.1
                    # would turn those into a terminating error
                    $ErrorActionPreference = "Continue"
                    $log = & $Dxc @DxcOptions -T $profile -E $stage.entry -Fo $tmp $hlsl 2>&1
                    $ErrorActionPreference = "Stop"
                    if ($LASTEXITCODE -ne 0) {
                        $log | ForEach-Object { Write-Host $_ }
                        throw "dxc failed: $($stage.entry) ($profile) in $hlsl"
                    }
                    $warnings += @($log | Where-Object { "$_" -match "warning:" }).Count
                    $bytes = [IO.File]::ReadAllBytes($tmp)
                    if ([Text.Encoding]::ASCII.GetString($bytes).Contains('type.$Globals')) {
                        $withGlobals += "$hlslRel|$($stage.entry)"
                    }
                    $name = "${prefix}_s$($table.Count)"
                    [void]$out.Append("const unsigned char ${name}[] = {`r`n").Append((Format-Bytes $bytes)).Append("};`r`n")
                    $table += "`t{ `"$($stage.entry)`", `"$($stage.profile)`", $name, sizeof($name) },"
                }
            }
        }
        if ($table.Count -eq 0) { $table += "`t{ nullptr, nullptr, nullptr, 0 }," }
        [void]$out.Append("const fxEmbeddedBytecode ${prefix}_bytecode[] = {`r`n").Append(($table -join "`r`n")).Append("`r`n};`r`n`r`n")

        # looked up by effect name: Special/Blur.effect.json is "Blur"
        $effectName = $file.Name -replace '\.effect\.json$', ''
        $source = $file.FullName.Substring($ShaderDir.Length).TrimStart('\', '/') -replace '\\', '/'
        $count = @($table | Where-Object { $_ -notmatch "nullptr" }).Count
        $effects += "`t{ `"$effectName`", `"$source`", (const char*)${prefix}_manifest, ${prefix}_bytecode, $count },"
        $e++
    }
}
finally {
    Remove-Item $tmp -ErrorAction SilentlyContinue
}

[void]$out.Append("}`r`n`r`n")
if ($effects.Count -gt 0) {
    [void]$out.Append("const fxEmbeddedEffect ${TableName}::k_Effects[] = {`r`n").Append(($effects -join "`r`n")).Append("`r`n};`r`n")
} else {
    [void]$out.Append("const fxEmbeddedEffect ${TableName}::k_Effects[] = { { nullptr, nullptr, nullptr, nullptr, 0 } };`r`n")
}
[void]$out.Append("const int ${TableName}::k_NumEffects = $($effects.Count);`r`n")
$deferredList = @($skipped | ForEach-Object { "`t`"$_`"," })
if ($deferredList.Count -eq 0) { $deferredList = @("`tnullptr,") }
[void]$out.Append("const char* const ${TableName}::k_Deferred[] = {`r`n").Append(($deferredList -join "`r`n")).Append("`r`n};`r`n")
[void]$out.Append("const int ${TableName}::k_NumDeferred = $($skipped.Count);`r`n")
[void]$out.Append("}`r`n")

$dir = Split-Path $OutFile -Parent
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
[IO.File]::WriteAllText($OutFile, $out.ToString())
foreach ($s in $skipped) { Write-Host "EmbedShadersVk: deferred $s" }
foreach ($g in $withGlobals) { Write-Host "EmbedShadersVk: `$Globals in $g" }
Write-Host "EmbedShadersVk: $($effects.Count) effect(s), $($skipped.Count) deferred stage(s), $warnings DXC warning(s) -> $OutFile"
