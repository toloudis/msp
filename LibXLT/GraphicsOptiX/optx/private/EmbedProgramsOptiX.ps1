<#
    EmbedProgramsOptiX.ps1

    Compiles every *.cu in -ProgramDir with nvcc to OptiX IR and writes one
    C++ file (namespace gox) holding each as a byte array, in the table
    optxEmbeddedPrograms::k_Programs, named after the file
    (optxRayQuery.cu is "optxRayQuery"). GraphicsOptiX's
    optxEmbeddedPrograms.cpp includes that file.

    -HostCompilerDir is the folder of the cl.exe nvcc preprocesses with
    (MSBuild passes the project's own). The nvcc options are fixed here:
    they must agree with the OptixModuleCompileOptions the programs are
    loaded with (line info only, no -G).

    Called from GraphicsOptiX.vcxproj (target EmbedOptixPrograms) before
    compiling. Written for Windows PowerShell 5.1.
#>
param(
    [Parameter(Mandatory = $true)][string]$ProgramDir,
    [Parameter(Mandatory = $true)][string]$OutFile,
    [Parameter(Mandatory = $true)][string]$Nvcc,
    [Parameter(Mandatory = $true)][string]$OptixInclude,
    [Parameter(Mandatory = $true)][string]$HostCompilerDir
)

$ErrorActionPreference = "Stop"

# compute_75 (Turing) is the oldest architecture CUDA 13 compiles for; the
# driver compiles OptiX IR on for the GPU in use
$NvccOptions = @(
    "--optix-ir", "--gpu-architecture=compute_75", "--std=c++17", "--use_fast_math", "-lineinfo", "-m64",
    "--compiler-bindir", $HostCompilerDir.TrimEnd('\'), "-I", $OptixInclude.TrimEnd('\'), "-I", $ProgramDir.TrimEnd('\')
)

if (-not (Test-Path $Nvcc)) { throw "nvcc.exe not found at '$Nvcc'" }

# C++ initializer list for a byte array, 32 bytes per line.
function Format-Bytes([byte[]]$bytes) {
    $sb = New-Object System.Text.StringBuilder
    for ($i = 0; $i -lt $bytes.Length; $i += 32) {
        $n = [Math]::Min(32, $bytes.Length - $i)
        $hex = [BitConverter]::ToString($bytes, $i, $n)
        [void]$sb.Append("`t0x").Append($hex.Replace("-", ",0x")).Append(",`r`n")
    }
    return $sb.ToString()
}

$ProgramDir = (Resolve-Path $ProgramDir).Path
$tmp = Join-Path ([IO.Path]::GetTempPath()) "optx-$([Guid]::NewGuid()).optixir"

$out = New-Object System.Text.StringBuilder
[void]$out.Append("// Generated by EmbedProgramsOptiX.ps1 from the *.cu files in`r`n")
[void]$out.Append("// $($ProgramDir.Replace('\', '/')). Do not edit.`r`n`r`n")
[void]$out.Append("namespace gox`r`n{`r`nnamespace`r`n{`r`n")

$table = @()
try {
    foreach ($file in (Get-ChildItem -Path $ProgramDir -Filter *.cu | Sort-Object Name)) {
        # nvcc (and cl.exe, which it runs) write progress and warnings to
        # stderr; with "Stop", PowerShell 5.1 would make those terminating
        $ErrorActionPreference = "Continue"
        $log = & $Nvcc @NvccOptions -o $tmp $file.FullName 2>&1
        $ErrorActionPreference = "Stop"
        if ($LASTEXITCODE -ne 0) {
            $log | ForEach-Object { Write-Host $_ }
            throw "nvcc failed: $($file.FullName)"
        }
        $log | Where-Object { "$_" -match "warning" } | ForEach-Object { Write-Host $_ }
        $bytes = [IO.File]::ReadAllBytes($tmp)
        $name = "k_p$($table.Count)"
        [void]$out.Append("const unsigned char ${name}[] = {`r`n").Append((Format-Bytes $bytes)).Append("};`r`n")
        $table += "`t{ `"$($file.BaseName)`", $name, sizeof($name) },"
    }
}
finally {
    Remove-Item $tmp -ErrorAction SilentlyContinue
}

[void]$out.Append("}`r`n`r`n")
$count = $table.Count
if ($count -eq 0) { $table += "`t{ nullptr, nullptr, 0 }," }
[void]$out.Append("const optxEmbeddedProgram optxEmbeddedPrograms::k_Programs[] = {`r`n").Append(($table -join "`r`n")).Append("`r`n};`r`n")
[void]$out.Append("const int optxEmbeddedPrograms::k_NumPrograms = $count;`r`n")
[void]$out.Append("}`r`n")

$dir = Split-Path $OutFile -Parent
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
[IO.File]::WriteAllText($OutFile, $out.ToString())
Write-Host "EmbedProgramsOptiX: $count program(s) -> $OutFile"
