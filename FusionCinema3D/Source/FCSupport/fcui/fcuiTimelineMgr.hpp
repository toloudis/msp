//============================================================================
//============================================================================
class plbkModePlayback;

//============================================================================
//============================================================================
class fcuiTimelineMgr
{
public:
	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	fcuiTimelineMgr();
	~fcuiTimelineMgr();

	//------------------------------------------------------------------------
	/// Return the current instance of the timeline mgr singleton
	//------------------------------------------------------------------------
	static fcuiTimelineMgr* Instance;

	//------------------------------------------------------------------------
	/// Set the start time of the timeline
	//------------------------------------------------------------------------
	void SetEndTime(const maTime& i_EndTime);

	//------------------------------------------------------------------------
	/// Get the time value of the end of the timeline
	//------------------------------------------------------------------------
	const maTime& GetEndTime() const;
	
	//------------------------------------------------------------------------
	/// Return whether or not we are playing the timeline
	//------------------------------------------------------------------------
	bool IsPlaying();
	
	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void Begin();
	
	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void End();
	
	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void Play();
	
	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void Pause();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void Rewind();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void FastFwd();
	
	//------------------------------------------------------------------------
	/// Increment the end time of the timeline
	//------------------------------------------------------------------------
	void IncrementTime(float i_IncrementAmount);
	
	//------------------------------------------------------------------------
	/// Decrement the end time of the timeline
	//------------------------------------------------------------------------
	void DecrementTime(float i_DecrementAmount);

	//------------------------------------------------------------------------
	/// Get the current playback time of the timeline
	//------------------------------------------------------------------------
	const maTime& GetCurrentTime() const;
	
	//------------------------------------------------------------------------
	/// Set the current playback time of the timeline
	//------------------------------------------------------------------------
	void SetCurrentTime(const maTime& i_NewTime);

private:
	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void LoadPlaybackMode();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	plbkModePlayback* GetPlaybackMode();

private:
	maTime m_CurrentTime;
	maTime m_EndTime;
	bool m_bPlaying;
};