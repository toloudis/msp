//========================================================================
//	free operator functions
//========================================================================
//========================================================================
inline maVector2d operator * ( const maVector2d& i_Vector, float i_s )
{
	return maVector2d( i_Vector.m_X * i_s, i_Vector.m_Y * i_s );
}

//========================================================================
//========================================================================
inline maVector2d operator * ( float i_s, const maVector2d& i_Vector )
{
	return maVector2d( i_Vector.m_X * i_s, i_Vector.m_Y * i_s );
}

//========================================================================
//========================================================================
inline maVector2d operator / ( const maVector2d& i_Vector, float i_s )
{
	return maVector2d( i_Vector.m_X / i_s, i_Vector.m_Y / i_s );
}



//========================================================================
//	default constructors
//========================================================================
inline maVector2d::maVector2d()
:	m_X(0),
	m_Y(0)
{
}

//========================================================================
//========================================================================
inline maVector2d::~maVector2d()
{
}



//========================================================================
//========================================================================
float 
maVector2d::GetX() const
{
	return m_X;
}

//========================================================================
//========================================================================
float 
maVector2d::GetY() const
{
	return m_Y;
}

//========================================================================
//========================================================================
void 
maVector2d::SetX( float i_X )
{
	m_X	= i_X;
}

//========================================================================
//========================================================================
void 
maVector2d::SetY( float i_Y )
{
	m_Y	= i_Y;
}

//========================================================================
//========================================================================
void 
maVector2d::Set( float i_X, float i_Y )
{ 
	m_X	= i_X; 
	m_Y	= i_Y; 
}

//========================================================================
//========================================================================
void 
maVector2d::Set( float i_v[2] )
{ 
	m_X	= i_v[0];
	m_Y	= i_v[1];
}
 
//========================================================================
//========================================================================
void 
maVector2d::Set( const maVector2d& i_vec2d )
{
	m_X	= i_vec2d.GetX();
	m_Y	= i_vec2d.GetY();
}

//========================================================================
//========================================================================
maVector2d&
maVector2d:: operator = ( const maVector2d& i_A )            // ASSIGNMENT (=)
{ 
	m_X	= i_A.GetX();
	m_Y	= i_A.GetY();

	return(*this);  
}


//========================================================================
//========================================================================
maVector2d 
maVector2d::operator + ( const maVector2d& i_A ) const       // ADDITION (+)
{ 
	maVector2d Sum( m_X + i_A.GetX(), m_Y + i_A.GetY() );

	return Sum; 
}


//========================================================================
//========================================================================
maVector2d 
maVector2d::operator - ( const maVector2d& i_A ) const       // SUBTRACTION (-)
{ 
	maVector2d Diff( m_X-i_A.GetX(), m_Y-i_A.GetY() );

	return Diff; 
}


//========================================================================
//========================================================================
float 
maVector2d::operator * ( const maVector2d& i_A ) const       // DOT-PRODUCT (*)
{ 
	float o_DotProd = m_X*i_A.GetX() + m_Y*i_A.GetY();

	return o_DotProd; 
}


//========================================================================
//========================================================================
bool 
maVector2d::operator == ( const maVector2d& i_A ) const	  // COMPARISON OPERATOR
{ 
	return ( (m_X == i_A.GetX()) && (m_Y == i_A.GetY()) ) ? true : false;	
}

//========================================================================
//========================================================================
inline bool 
maVector2d::operator != ( const maVector2d& i_A ) const
{
	return  (m_X != i_A.GetX()) ||
			(m_Y != i_A.GetY());
}


//========================================================================
//========================================================================
void 
maVector2d::operator += ( const maVector2d& i_A )              // ACCUMULATED VECTOR ADDITION (+=)
{ 
	m_X	+= i_A.GetX(); 
	m_Y	+= i_A.GetY();
}


//========================================================================
//========================================================================
void 
maVector2d::operator -= ( const maVector2d& i_A )              // ACCUMULATED VECTOR SUBTRACTION (+=)
{ 
	m_X	-= i_A.GetX();
	m_Y	-= i_A.GetY(); 
}


//========================================================================
//========================================================================
void 
maVector2d::operator *= ( float i_s )              // ACCUMULATED SCALAR MULT (*=)
{ 
	m_X	*= i_s;
	m_Y	*= i_s;
}


//========================================================================
//========================================================================
void 
maVector2d::operator /= ( float i_s )              // ACCUMULATED SCALAR DIV (/=)
{ 
	m_X	/= i_s;
	m_Y	/= i_s;
}


//========================================================================
//========================================================================
maVector2d 
maVector2d::operator - () const                 // NEGATION (-)
{ 
	maVector2d o_Negated( -m_X, -m_Y );

	return o_Negated;
}

//========================================================================
//========================================================================
const float& 
maVector2d::operator [] ( int i_Index ) const         // ALLOWS VECTOR ACCESS AS AN ARRAY.
{  
	switch (i_Index)
	{
		case 0:
			return m_X;
		case 1:
			return m_Y;
		default:
			DBG_ASSERT1(false, "Index out of range %d", i_Index);
			return m_X;
	}
}

//========================================================================
//========================================================================
float&
maVector2d::operator [] ( int i_Index )		         // ALLOWS VECTOR ACCESS AS AN ARRAY.
{  
	switch (i_Index)
	{
		case 0:
			return m_X;
		case 1:
			return m_Y;
		default:
			DBG_ASSERT1(false, "Index out of range %d", i_Index);
			return m_X;
	}
}


