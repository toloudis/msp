//========================================================================
//========================================================================
float 
maVector2d::Length() const                     // LENGTH OF VECTOR
{ 
	return ( (float)sqrt( m_X*m_X + m_Y*m_Y ) ); 
}


//========================================================================
//========================================================================
float 
maVector2d::LengthSqr() const                  // LENGTH OF VECTOR (SQUARED)
{ 
	return ( m_X*m_X + m_Y*m_Y );
}


//========================================================================
//========================================================================
void 
maVector2d::Normalize()							 // NORMALIZE VECTOR
{ 
	float L = this->Length();
	
	//	Divide the vector by the length
	//
	if ( L > 0 ) 
	{ 
		m_X	/= L; 
		m_Y	/= L; 
	}
}

