void mslVisitorHLSL::var_ref(mslQualifiedName *name,const IDeclaration *declaration)
{
	//bga - Have to give some sort of prefix to input variables
	// because they become global inputs. Using "sgpu_" for now, but maybe use "g_"?
	if (declaration && declaration->is_input())
		print_code("sgpu_");

    for(int i = 0; i < name->size(); i++) {
        if(i)
            print_code("__");
        print_code("%s",(*name)[i]);
    }
}

