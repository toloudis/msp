void mslVisitorHLSL::parameter_declaration(
    int position,
    const char *mode,
    const mslQualifiedName *type,
    const char *name,
    const char *dimension)
{
    if(position)
	{
        print_code(",");
		// each parameter on a new line
		print_code("\n");
		print_tabs(1);
	}
    if(mode)
        print_code("%s ",mode);
    for(int i = 0; i < type->size(); i++) {
        if(i)
            print_code("__");
        print_code("%s",(*type)[i]);
    }
    print_code(" %s",name);
    if(dimension)
        print_code("[%s]",dimension);
}

