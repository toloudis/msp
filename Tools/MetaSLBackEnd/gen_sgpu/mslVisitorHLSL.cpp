void mslVisitorHLSL::op(IType *type,const char *name)
{
    if(!strcmp(name,"."))
        print_code(".");
    else if(!strcmp(name,"[]"))
        print_code("[");
    else
        print_code(" %s ",name);
}

void mslVisitorHLSL::begin_pre_op(
    IType *type,const char *name,bool parentheses)
{
    if(parentheses)
        print_code("(");
    print_code("%s",name);
}

void mslVisitorHLSL::end_pre_op(
    IType *type,const char *name,bool parentheses)
{
    if(parentheses)
        print_code(")");
}

void mslVisitorHLSL::begin_post_op(
    IType *type,const char *name,bool parentheses)
{
    if(parentheses)
        print_code("(");
}

void mslVisitorHLSL::end_post_op(
    IType *type,const char *name,bool parentheses)
{
    print_code("%s",name);
    if(parentheses)
        print_code(")");
}

void mslVisitorHLSL::begin_bin_op(
    IType *type,const char *name,bool parentheses)
{
    if(strcmp(name,"[]") && parentheses)
        print_code("(");
}

void mslVisitorHLSL::end_bin_op(
    IType *type,const char *name,bool parentheses)
{
    if(strcmp(name,"[]")) {
        if(parentheses)
            print_code(")");
    } else {
        print_code("]");
    }
}

