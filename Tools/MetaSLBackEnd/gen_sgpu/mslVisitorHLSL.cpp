void mslVisitorHLSL::begin_call(const mslQualifiedName *name,
                            const IDeclaration *declaration,
							bool i_bRequiresState)
{
    for(int i = 0; i < name->size(); i++) {
        if(i)
            print_code("__");
        print_code("%s",(*name)[i]);
    }
    print_code("(");

	//bga - adding in state and light when calling one of the shader's methods.
	//if(declaration && (declaration->is_method())) {
	if (i_bRequiresState) {
		print_code("state,light");
	}
}

