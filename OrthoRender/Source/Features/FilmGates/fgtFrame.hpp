#define FGT_FRAME_HPP

#ifndef API3D_OBJECT_HPP
#include "Tool/api3d/api3dObject.hpp"
#endif

#include <string>


//============================================================================
//============================================================================
class fgtFrame
{
	public:
		//--------------------------------------------------------------------
		//	Constructor
		//--------------------------------------------------------------------
		fgtFrame(int i_Width, int i_Height, char* i_MenuName);

		//--------------------------------------------------------------------
		//	Destructor
		//--------------------------------------------------------------------
		virtual ~fgtFrame();

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		int GetWidth()
		{
			return m_Width;
		}
		int GetHeight()
		{
			return m_Height;
		}
		const std::string& GetMenuDesc()
		{
			return m_MenuDesc;
		}

		//--------------------------------------------------------------------
		//	Show() - Render the shape or not
		//--------------------------------------------------------------------
		virtual void Show(bool i_bVisible = true);

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		bool IsVisible();

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		void Resize();

	private:
		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		void CreateFrame();

	private:
		int m_Width;
		int m_Height;

		api3dObject* m_pFrameObject;

		std::string m_MenuDesc;
};
