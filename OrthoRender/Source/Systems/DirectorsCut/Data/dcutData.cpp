#include "Systems/DirectorsCut/Data/dcutData.hpp"

#include "Core/env/envSTLHelpers.hpp"


//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
dcutCueData::dcutCueData()
:	m_Name("Name")
{
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
dcutCueData::dcutCueData(const dcutCueData& i_Data)
:	m_Name("Name")
{
	(*this) = i_Data;
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
dcutCueData::~dcutCueData()
{
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
bool dcutCueData::operator == (const dcutCueData& i_Item)
{
	return (this->m_Name == i_Item.m_Name);
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
dcutCueData& dcutCueData::operator=(const dcutCueData& i_Data)
{
	if (this == &i_Data) return *this;

	this->m_Name			= i_Data.m_Name;

	return *this;
}



