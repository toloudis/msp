#include "Systems/Groups/Data/grupData.hpp"

#include "Core/env/envSTLHelpers.hpp"

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
grupData::grupData()
:	m_Name("Name")
{
}

//-------------------------------------------------
//-------------------------------------------------
grupData::grupData(const grupData& i_Data)
:	m_Name("Name")
{
	(*this) = i_Data;
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
grupData::~grupData()
{
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
bool grupData::operator == (const grupData& i_Item)
{
	return (this->m_Name == i_Item.m_Name);
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
grupData& grupData::operator=(const grupData& i_Data)
{
	if (this == &i_Data) return *this;

	m_Name			= i_Data.m_Name;
	
	m_Objects		= i_Data.m_Objects;

	return *this;
}

//----------------------------------------------------------------------------
//----------------------------------------------------------------------------
void grupGroupsData::Clear()
{
	m_Items.clear();
}
