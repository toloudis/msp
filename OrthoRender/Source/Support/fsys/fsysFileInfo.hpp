#ifdef FSYS_FILEINFO_HPP
#error fsysFileInfo.hpp multiply included
#endif
#define FSYS_FILEINFO_HPP

#ifndef IT_STRING_HPP
#include "Core/it/itString.hpp"
#endif

#ifndef FS_LOCATOR_HPP
#include "Core/fs/fsLocator.hpp"
#endif


//============================================================================
//============================================================================
class fsysFileInfo
{
public:
	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	fsysFileInfo();

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	inline void SetFilename( const itString& i_Filename );

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	inline const itString& GetFilename() const;

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	inline void SetFilePath( const fsLocator& i_FilePath );

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	inline const fsLocator& GetFilePath() const;

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	void operator =(const fsysFileInfo& i_Item);

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	bool operator ==(const fsysFileInfo& i_Item);

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	bool operator >=(const fsysFileInfo& i_Item) const;

	//------------------------------------------------------------------------
	//------------------------------------------------------------------------
	bool operator <=(const fsysFileInfo& i_Item) const;

private:
	itString	m_Filename;
	fsLocator	m_FilePath;
};


//------------------------------------------------------------------------
//------------------------------------------------------------------------
inline void fsysFileInfo::SetFilename( const itString& i_Filename )
{
	m_Filename = i_Filename;
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
inline const itString& fsysFileInfo::GetFilename() const
{
	return m_Filename;
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
inline void fsysFileInfo::SetFilePath( const fsLocator& i_FilePath )
{
	m_FilePath = i_FilePath;
}

//------------------------------------------------------------------------
//------------------------------------------------------------------------
inline const fsLocator& fsysFileInfo::GetFilePath() const
{
	return m_FilePath;
}

