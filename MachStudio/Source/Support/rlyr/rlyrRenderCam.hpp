#ifdef RLYR_RENDERCAM_HPP
#error rlyrRenderCam.hpp multiply included
#endif
#define RLYR_RENDERCAM_HPP

#ifndef G3D_PREFS_HPP
#include "Graphics/g3d/g3dPrefs.hpp"
#endif

#include <vector>
#include <map>


//============================================================================
//	Forward References
//============================================================================
class rlyrObject;
class rlyrRenderLayer;
class nameString;
class nameObject;
class captRenderOutputObject;
class captRenderOutputData;
class rprfPrefsObject;
class rprfPrefsData;


//============================================================================
// A RenderCam
//============================================================================
class rlyrRenderCam
{
public:
	std::vector<rlyrRenderLayer*> m_RenderLayers;

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	rlyrRenderCam(nameObject* i_NameObject);

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	virtual ~rlyrRenderCam();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	void SetName(const nameString& i_Name);

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	nameString GetName();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	void GetLayerNames(std::vector<nameString>& o_RenderLayers);

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	rlyrRenderLayer* GetLayerByName(const nameString& i_LayerName);

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	void RemoveLayer(const nameString& i_LayerName);

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	void RemoveAllLayers();

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	void AddLayer(rlyrRenderLayer* i_RenderLayer);

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	void SetLayerActiveState(const nameString& i_LayerName, bool i_ActiveState);

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	void SetAllLayersActiveState(bool i_ActiveState);
	
	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	bool GetLayerActiveState(const nameString &i_LayerName);
	
	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	void UpdateLayerName(const nameString& i_OldName, const nameString& i_NewName);

	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	void ApplyLayerPrefs(int i_LayerIndex);

	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	const g3dPrefs::g3dRenderPrefs& GetLayerActualData(int i_LayerIndex);

	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	rprfPrefsObject* GetLayerPrefs(const nameString& i_LayerName);

	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	void SetLayerPrefs(const nameString& i_LayerName, rprfPrefsData& i_NewPrefs);

	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	captRenderOutputObject* GetLayerCaptureOptions(const nameString& i_LayerName);

	//----------------------------------------------------------------------------
	//----------------------------------------------------------------------------
	void SetLayerCaptureOptions(const nameString& i_LayerName, captRenderOutputData& i_NewOptions);

	//--------------------------------------------------------------------
	// when adding an object, add to all layers
	//--------------------------------------------------------------------
	void AddObjectToLayers(rlyrObject* i_Object);

	//--------------------------------------------------------------------
	// remove an object from all layers
	//--------------------------------------------------------------------
	void RemoveObjectFromLayers(rlyrObject* i_Object);

	//--------------------------------------------------------------------
	// get the object name, visible flag pairing for the specified layer
	//--------------------------------------------------------------------
	void GetLayerObjectVisibility(int i_LayerIndex, std::map<nameString, bool>& o_ObjectStatus);

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	void SetObjectState(const nameString& i_LayerName, rlyrObject* i_Object, bool i_Active);

	//--------------------------------------------------------------------
	//--------------------------------------------------------------------
	bool GetObjectState(const nameString& i_LayerName, rlyrObject* i_Object);

public:
	nameObject* m_NameObject;
};


