#define FGT_FRAME_HPP

#ifndef API3D_OBJECTSIMPLE_HPP
#include "Tool/api3d/api3dObjectSimple.hpp"
#endif

#include <string>


//============================================================================
//============================================================================
class gpxSceneObject;


//============================================================================
//============================================================================
class fgtFrame
{
	public:
		//--------------------------------------------------------------------
		//	Constructor
		//--------------------------------------------------------------------
		fgtFrame();

		//--------------------------------------------------------------------
		//	Destructor
		//--------------------------------------------------------------------
		virtual ~fgtFrame();

		//--------------------------------------------------------------------
		///	Get the width of the frame
		//--------------------------------------------------------------------
		float GetWidth()
		{
			return m_Width;
		}
		//--------------------------------------------------------------------
		///	Get the height of the frame
		//--------------------------------------------------------------------
		float GetHeight()
		{
			return m_Height;
		}
		//--------------------------------------------------------------------
		///	Get the ratio of the frame
		//--------------------------------------------------------------------
		float GetRatio()
		{
			return m_Ratio;
		}

		//--------------------------------------------------------------------
		///	Set the horizontal and veritcal percent.
		//--------------------------------------------------------------------
		void SetPercentages( float i_HorizontalPct, float i_VerticalPct );

		//--------------------------------------------------------------------
		///	Set the color
		//--------------------------------------------------------------------
		void SetColor( maFloatRGBA i_Color );

		//--------------------------------------------------------------------
		//	Show() - Render the shape or not
		//--------------------------------------------------------------------
		virtual void Show(bool i_bVisible = true);

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		bool IsVisible();

		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		void Resize();

	private:
		//--------------------------------------------------------------------
		//--------------------------------------------------------------------
		void create_frame();

		//--------------------------------------------------------------------
		///	Calculate the size of the frame based on the view size and
		///	horizontal and vertical percentages.
		//--------------------------------------------------------------------
		void calculate_frame_size(float& o_TargetX, float& o_TargetY);

	private:
		float m_Width;
		float m_Height;
		float m_Ratio;

		float m_HorizontalPercent;
		float m_VerticalPercent;

		api3dObjectSimple* m_pFrameObject;
		gpxSceneObject* m_pFrameObjectProxy;
};
